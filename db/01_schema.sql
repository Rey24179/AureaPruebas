CREATE EXTENSION IF NOT EXISTS pgcrypto;

SET client_encoding = 'UTF8';


--  BASE

CREATE TABLE sucursal (
    sucursal_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_sucursal varchar(40)  NOT NULL UNIQUE CHECK (btrim(nombre_sucursal) <> ''),
    telefono varchar(15)  NOT NULL,
    direccion varchar(100) NOT NULL,
    capacidad smallint NOT NULL CHECK (capacidad > 0)
);

CREATE TABLE rol (
    rol_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol varchar(30) NOT NULL UNIQUE CHECK (btrim(rol) <> '')
);

CREATE TABLE empleado (
    empleado_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_empleado varchar(30) NOT NULL CHECK (btrim(nombre_empleado) <> ''),
    apellido varchar(30) NOT NULL CHECK (btrim(apellido) <> ''),
    fecha_contratacion date NOT NULL DEFAULT CURRENT_DATE,
    rol_id integer NOT NULL REFERENCES rol,
    sucursal_id integer NOT NULL REFERENCES sucursal,
    estado text NOT NULL DEFAULT 'Activo'CHECK (estado IN ('Activo','Inactivo'))
);

-- Requisito 1: sign in y log in con roles.
CREATE TABLE usuario (
    usuario_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id integer NOT NULL UNIQUE REFERENCES empleado,
    nombre_usuario text NOT NULL UNIQUE CHECK (nombre_usuario ~ '^[a-z0-9._]{4,30}$'),
    password_hash text NOT NULL,
    estado text NOT NULL DEFAULT 'Activo' CHECK (estado IN ('Activo','Inactivo')),
    creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_login timestamptz
);

-- Un cliente puede no querer dar sus datos, que es lo normal en una
-- cafeteria. Por eso TODOS los campos de identificacion son opcionales.
--
-- Lo unico que se exige es que la fila sirva para algo: nombre, telefono
-- o correo, al menos uno. Sin eso la fila seria un ID vacio, se crearia
-- una nueva en cada visita y el reporte de clientes frecuentes contaria
-- a la misma persona muchas veces.
--
-- El cliente que no quiere dar NADA no necesita fila: orden.cliente_id
-- es nulo y la venta se registra igual.
CREATE TABLE cliente (
    cliente_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nit varchar(13) CHECK (nit      IS NULL OR btrim(nit)      <> ''),
    nombre varchar(30) CHECK (nombre   IS NULL OR btrim(nombre)   <> ''),
    apellido varchar(30) CHECK (apellido IS NULL OR btrim(apellido) <> ''),
    telefono varchar(15) CHECK (telefono IS NULL OR btrim(telefono) <> ''),
    correo varchar(60) CHECK (correo   IS NULL OR btrim(correo)   <> ''),
    creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT cliente_identificable CHECK (nombre IS NOT NULL OR telefono IS NOT NULL OR correo IS NOT NULL)
);


-- UNIDADES Y CONVERSION
--
-- Las recetas se escriben en g y ml porque asi se cocina. El inventario
-- se lleva en kg y L porque asi se compra. Esta tabla es el puente, y
-- sin ella el descuento por venta restaria mil veces de mas.

CREATE TABLE unidad_conversion (
    unidad_origen varchar(4) NOT NULL,
    unidad_destino varchar(4) NOT NULL,
    factor numeric(12,6) NOT NULL CHECK (factor > 0),
    PRIMARY KEY (unidad_origen, unidad_destino)
);
COMMENT ON TABLE unidad_conversion IS 'cantidad_en_destino = cantidad_en_origen * factor';


-- MENU E INSUMOS

CREATE TABLE platillo (
    platillo_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_platillo varchar(50) NOT NULL CHECK (btrim(nombre_platillo) <> ''),
    precio numeric(8,2) NOT NULL CHECK (precio > 0),
    categoria varchar(15) NOT NULL CHECK (categoria IN ('Plato Fuerte','Postre','Bebida','Entrada')),
    es_vegetariano boolean NOT NULL DEFAULT false,
    disponible boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX platillo_nombre_unico ON platillo (lower(btrim(nombre_platillo)));

CREATE TABLE ingrediente (
    ingrediente_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_ingrediente varchar(60) NOT NULL CHECK (btrim(nombre_ingrediente) <> ''),
    categoria varchar(25) NOT NULL,
    unidad_medida varchar(4) NOT NULL CHECK (unidad_medida IN ('kg','g','L','ml','ud')),
    -- stock_minimo y stock_referencia sostienen la regla del 15%.
    -- Ninguno puede ser NULL: un NULL apaga la alerta en silencio.
    stock_minimo numeric(12,3) NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    stock_referencia numeric(12,3) NOT NULL CHECK (stock_referencia > 0 AND stock_referencia >= stock_minimo)
);
CREATE UNIQUE INDEX ingrediente_nombre_unico ON ingrediente (lower(btrim(nombre_ingrediente)));

-- Requisito: los insumos se manejan a nivel de ingrediente, no de plato.
-- Esta tabla es lo unico que conecta una venta con el inventario.
CREATE TABLE detalle_receta (
    platillo_id integer NOT NULL REFERENCES platillo,
    ingrediente_id integer NOT NULL REFERENCES ingrediente,
    cantidad numeric(10,3) NOT NULL CHECK (cantidad > 0),
    unidad_medida varchar(4) NOT NULL CHECK (unidad_medida IN ('kg','g','L','ml','ud')),
    PRIMARY KEY (platillo_id, ingrediente_id)
);

-- INVENTARIO
CREATE TABLE lote_inventario (
    lote_id varchar(30) PRIMARY KEY CHECK (btrim(lote_id) <> ''),
    ingrediente_id integer NOT NULL REFERENCES ingrediente,
    sucursal_id integer NOT NULL REFERENCES sucursal,
    fecha_ingreso date NOT NULL DEFAULT CURRENT_DATE,
    fecha_vencimiento date NOT NULL,
    cantidad_disponible numeric(12,3) NOT NULL DEFAULT 0 CHECK (cantidad_disponible >= 0),
    CONSTRAINT lote_vence_despues_de_ingresar  CHECK (fecha_vencimiento >= fecha_ingreso)
);

CREATE TABLE movimiento_inventario (
    movimiento_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id varchar(30) NOT NULL REFERENCES lote_inventario,
    fecha_hora timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo_movimiento text NOT NULL CHECK (tipo_movimiento IN ('Entrada','Salida','Merma','Ajuste')),
    cantidad         numeric(12,3) NOT NULL CHECK (cantidad >= 0),
    -- Los tres campos siguientes los calcula el trigger, no la aplicacion.
    variacion numeric(12,3) NOT NULL,
    stock_anterior numeric(12,3) NOT NULL,
    stock_resultante numeric(12,3) NOT NULL CHECK (stock_resultante >= 0),
    empleado_id integer REFERENCES empleado,
    responsable varchar(60),
    motivo varchar(200) NOT NULL CHECK (btrim(motivo) <> ''),
    CONSTRAINT movimiento_tiene_responsable CHECK (empleado_id IS NOT NULL OR btrim(COALESCE(responsable,'')) <> '')
);


-- MESAS Y RESERVAS

CREATE TABLE mesa (
    mesa_id smallint NOT NULL,
    sucursal_id integer  NOT NULL REFERENCES sucursal,
    capacidad smallint NOT NULL CHECK (capacidad > 0),
    -- Estado FISICO de la mesa. Que este reservada no se guarda aqui:
    -- una mesa no esta reservada en absoluto, esta reservada de 19:00
    -- a 20:30 del jueves, y eso se calcula desde reserva.
    estado  text NOT NULL DEFAULT 'Disponible' CHECK (estado IN ('Disponible','Ocupada','Mantenimiento')),
    PRIMARY KEY (mesa_id, sucursal_id)
);

CREATE TABLE reserva (
    reserva_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id integer NOT NULL REFERENCES cliente,
    sucursal_id integer NOT NULL REFERENCES sucursal,
    fecha_reserva date NOT NULL,
    hora_reserva time NOT NULL,
    duracion_min smallint NOT NULL DEFAULT 90 CHECK (duracion_min BETWEEN 30 AND 240),
    estado text NOT NULL DEFAULT 'Pendiente' CHECK (estado IN ('Pendiente','Confirmada','Cancelada','Completada')),
    personas smallint NOT NULL CHECK (personas > 0),
    observaciones varchar(200),
    creada_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (reserva_id, sucursal_id)
);

CREATE TABLE reserva_mesa (
    reserva_id integer  NOT NULL,
    mesa_id smallint NOT NULL,
    sucursal_id integer  NOT NULL,
    PRIMARY KEY (reserva_id, mesa_id, sucursal_id),
    FOREIGN KEY (reserva_id, sucursal_id) REFERENCES reserva (reserva_id, sucursal_id)
        ON DELETE CASCADE,
    FOREIGN KEY (mesa_id, sucursal_id) REFERENCES mesa (mesa_id, sucursal_id)
);

-- Requisito 4: preferencias del cliente, por ejemplo platos favoritos.
-- Alimenta el reporte iii.
CREATE TABLE preferencia_cliente (
    cliente_id integer NOT NULL REFERENCES cliente ON DELETE CASCADE,
    platillo_id integer NOT NULL REFERENCES platillo,
    nota varchar(120),
    PRIMARY KEY (cliente_id, platillo_id)
);

-- VENTAS
CREATE TABLE orden (
    orden_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    empleado_id integer NOT NULL REFERENCES empleado,
    sucursal_id integer NOT NULL REFERENCES sucursal,
    -- Nullable a proposito: una orden de barra puede no tener cliente.
    -- Con cliente, alimenta el historial y los reportes ii y iii.
    cliente_id integer REFERENCES cliente,
    reserva_id integer REFERENCES reserva,
    estado text NOT NULL DEFAULT 'Pendiente' CHECK (estado IN ('Pendiente','Completada','Cancelada'))
);

-- Unica fuente de verdad de lo que se vendio.
CREATE TABLE detalle_orden (
    orden_id integer NOT NULL REFERENCES orden ON DELETE CASCADE,
    platillo_id integer NOT NULL REFERENCES platillo,
    cantidad smallint NOT NULL CHECK (cantidad > 0),
    precio_unitario numeric(10,2) NOT NULL CHECK (precio_unitario >= 0),
    observaciones varchar(120),
    PRIMARY KEY (orden_id, platillo_id)
);

CREATE TABLE factura (
    factura_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id integer NOT NULL UNIQUE REFERENCES orden,
    cliente_id integer REFERENCES cliente,
    fecha_hora_emision timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    nit varchar(13) NOT NULL DEFAULT 'CF',
    nombre_facturacion varchar(50) NOT NULL DEFAULT 'Consumidor Final',
    total numeric(10,2) NOT NULL DEFAULT 0 CHECK (total >= 0)
);

CREATE TABLE detalle_factura (
    factura_id integer NOT NULL REFERENCES factura ON DELETE CASCADE,
    numero_linea smallint NOT NULL,
    platillo_id integer NOT NULL REFERENCES platillo,
    descripcion varchar(50) NOT NULL,
    cantidad smallint NOT NULL CHECK (cantidad > 0),
    precio_unitario numeric(10,2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal numeric(10,2) NOT NULL CHECK (subtotal >= 0),
    PRIMARY KEY (factura_id, numero_linea)
);

-- BITACORA 
-- Una sola tabla para toda la base. El usuario se toma de la variable
-- de sesion aurea.usuario, que la aplicacion fija despues del login
-- con  SET LOCAL aurea.usuario = 'kristel.admin'.

CREATE TABLE bitacora (
    bitacora_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tabla text NOT NULL,
    operacion text NOT NULL CHECK (operacion IN ('INSERT','UPDATE','DELETE')),
    usuario text NOT NULL,
    anterior jsonb,
    nuevo jsonb
);
