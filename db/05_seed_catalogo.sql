-- ---------------------------------------------------------------------
-- Verificacion: toda receta debe poder convertirse al inventario
-- ---------------------------------------------------------------------
DO $$
DECLARE v_malas integer;
BEGIN
    SELECT count(*) INTO v_malas
    FROM detalle_receta dr JOIN ingrediente i USING (ingrediente_id)
    WHERE dr.unidad_medida <> i.unidad_medida
    AND NOT EXISTS (SELECT 1 FROM unidad_conversion
                        WHERE unidad_origen = dr.unidad_medida
                          AND unidad_destino = i.unidad_medida);
    IF v_malas > 0 THEN
        RAISE EXCEPTION '% lineas de receta no tienen conversion posible.', v_malas;
    END IF;
    RAISE NOTICE 'Catalogo cargado: % insumos, % platillos, % lineas de receta.',
        (SELECT count(*) FROM ingrediente),
        (SELECT count(*) FROM platillo),
        (SELECT count(*) FROM detalle_receta);
END $$;
